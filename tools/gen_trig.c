/* Build-time generator for the engine trig tables (tech.md, Simulation).
 * Host program: floating point is allowed here and only here. Writes
 * trig_tables.h into the build tree; the output is never committed.
 *
 *   finesine[5120]    fix_t sin over 4096 fine angles + a quarter turn so
 *                     cosine is finesine[i + 1024]. round-to-nearest.
 *   tantoangle[2049]  angle_t atan(i / 2048) for slopes 0..1, round-to-nearest.
 *
 * Usage: gen_trig <output.h>
 */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

#define PI 3.14159265358979323846
#define FINEANGLES 4096
#define SLOPERANGE 2048

int main(int argc, char **argv)
{
    if (argc != 2) {
        fprintf(stderr, "usage: gen_trig <output.h>\n");
        return 1;
    }
    FILE *f = fopen(argv[1], "w");
    if (!f) {
        perror(argv[1]);
        return 1;
    }
    fprintf(f, "/* Generated by tools/gen_trig.c. Do not edit, do not commit. */\n");
    fprintf(f, "#ifndef ENGINE_TRIG_TABLES_H\n#define ENGINE_TRIG_TABLES_H\n\n");

    fprintf(f, "static const fix_t finesine[%d] = {\n", FINEANGLES + FINEANGLES / 4);
    for (int i = 0; i < FINEANGLES + FINEANGLES / 4; i++) {
        long v = lround(sin((double)i * 2.0 * PI / FINEANGLES) * 65536.0);
        fprintf(f, "%s%ld,%s", (i % 8) ? " " : "    ", v, (i % 8 == 7) ? "\n" : "");
    }
    fprintf(f, "\n};\n\n");

    fprintf(f, "static const angle_t tantoangle[%d] = {\n", SLOPERANGE + 1);
    for (int i = 0; i <= SLOPERANGE; i++) {
        long v = lround(atan((double)i / SLOPERANGE) * 65536.0 / (2.0 * PI));
        fprintf(f, "%s%ld,%s", (i % 8) ? " " : "    ", v, (i % 8 == 7) ? "\n" : "");
    }
    fprintf(f, "\n};\n\n#endif\n");

    if (fclose(f) != 0) {
        perror(argv[1]);
        return 1;
    }
    return 0;
}
