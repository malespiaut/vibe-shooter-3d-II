#!/usr/bin/env python3
"""Generate assets/src/palette/catlantis.gpl from the art-bible palette plan.

The .gpl output is committed as the source of truth; this script is kept so
the ramp maths stays reproducible. Re-running it must not change existing
entries once M1 lands (art-bible: entries never move or change).

Ramp maths (docs/design/art-bible.md, "Palette plan"):
- Each ramp runs dark -> light between its two anchor colours.
- Oklab L is stepped evenly between the anchors' L.
- a/b are interpolated linearly, chroma gets a mid-ramp boost
  (1 + boost * sin(pi * t)) so the middle of a saturated ramp does not go
  muddy, and a warm offset (+a, +b scaled by (1 - t)) makes the dark end
  slightly warmer so shading looks painted rather than grey-dimmed.
- Out-of-gamut colours are mapped by reducing chroma at constant L and hue.

Usage: python3 tools/make_palette.py [out.gpl]
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bast import oklab_to_srgb, srgb_to_oklab  # noqa: E402  (libbast, the only Oklab code)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "assets", "src", "palette", "catlantis.gpl")

# Warm offset in Oklab (a, b) applied fully at the darkest entry, zero at the
# lightest. Small on purpose: "slightly warmer at the dark end".
WARM_A = 0.002
WARM_B = 0.006

# name, first index, count, dark anchor, light anchor, mid-ramp chroma boost
RAMPS = [
    ("gray",   2,   16, "#101010", "#E8E8E8", 0.0),
    ("steel",  18,  16, "#0E1218", "#C8D4E0", 0.15),
    ("beige",  34,  16, "#18140F", "#EFE4CF", 0.15),
    ("sand",   50,  16, "#20160A", "#F6E2A0", 0.30),
    ("brown",  66,  16, "#120A06", "#C8946A", 0.30),
    ("gold",   82,  12, "#2A1A04", "#FFE868", 0.35),
    ("red",    94,  16, "#1A0202", "#FF7060", 0.45),
    ("green",  110, 12, "#041404", "#9CF08C", 0.35),
    ("blue",   122, 12, "#040A20", "#8CC0FF", 0.35),
    ("violet", 134, 12, "#12041E", "#E0A0FF", 0.35),
    ("orange", 146, 12, "#200802", "#FFC070", 0.40),
    ("cyan",   158, 12, "#021416", "#A0FFF4", 0.30),
    ("olive",  170, 12, "#0E1004", "#C8CC80", 0.25),
    ("fur",    182, 12, "#1E0C04", "#FFC88C", 0.35),
    ("pink",   194, 10, "#200810", "#FFC0C8", 0.35),
    ("indigo", 204, 12, "#06061A", "#9090D8", 0.30),
]

RESERVED_FIRST, RESERVED_COUNT = 216, 21

# Warm near-blacks between black (Oklab L 0) and the darkest ramp entries
# (L ~0.14-0.17). Hand-picked, not ramp maths: sRGB compresses this range so
# much that the anchor interpolation cannot place them. Without them the
# colormap's darkest rows fall onto indigo_00 (navy) before black, which breaks
# the art-bible rule "darkness is warm brown, not cold gray".
SHADOW_FIRST = 237
SHADOW = [(2, 2, 1), (4, 3, 2), (7, 5, 3)]

FULLBRIGHT = [
    ("fb_sun", "#FFFFF0"), ("fb_yellow", "#FFF040"), ("fb_gold", "#FFD020"),
    ("fb_orange", "#FF9020"), ("fb_fire", "#FF5010"), ("fb_red", "#FF2020"),
    ("fb_red_dim", "#B01010"), ("fb_cyan", "#40FFF0"), ("fb_cyan_dim", "#10B0B0"),
    ("fb_green", "#40FF40"), ("fb_blue", "#4080FF"), ("fb_violet", "#C060FF"),
    ("fb_white", "#F0F0FF"), ("fb_amber", "#FFB040"), ("fb_pink", "#FF60A0"),
]


def hex_to_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def ramp(dark, light, count, boost):
    L0, a0, b0 = srgb_to_oklab(hex_to_rgb(dark))
    L1, a1, b1 = srgb_to_oklab(hex_to_rgb(light))
    out = []
    for i in range(count):
        t = i / (count - 1)
        L = L0 + (L1 - L0) * t
        a = a0 + (a1 - a0) * t
        b = b0 + (b1 - b0) * t
        k = 1.0 + boost * math.sin(math.pi * t)
        a, b = a * k, b * k
        w = 1.0 - t
        a += WARM_A * w
        b += WARM_B * w
        out.append(oklab_to_srgb((L, a, b)))
    return out


def build():
    entries = [None] * 256
    entries[0] = ((0, 0, 0), "black")
    entries[1] = ((255, 255, 255), "white")
    for name, first, count, dark, light, boost in RAMPS:
        for i, rgb in enumerate(ramp(dark, light, count, boost)):
            entries[first + i] = (rgb, "%s_%02d" % (name, i))
    for i in range(RESERVED_COUNT):
        entries[RESERVED_FIRST + i] = ((0, 0, 0), "reserved_%02d" % i)
    for i, rgb in enumerate(SHADOW):
        entries[SHADOW_FIRST + i] = (rgb, "shadow_%02d" % i)
    for i, (name, h) in enumerate(FULLBRIGHT):
        entries[240 + i] = (hex_to_rgb(h), name)
    entries[255] = ((255, 0, 255), "transparent")
    assert all(e is not None for e in entries)
    return entries


def write_gpl(entries, path):
    lines = ["GIMP Palette", "Name: Catlantis", "Columns: 16",
             "# Generated by tools/make_palette.py; see docs/design/art-bible.md"]
    for (r, g, b), name in entries:
        lines.append("%3d %3d %3d\t%s" % (r, g, b, name))
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    entries = build()
    named = [rgb for rgb, n in entries if not n.startswith("reserved_")]
    dups = len(named) - len(set(named))
    if dups:
        print("make_palette: %d duplicate colours among named entries" % dups,
              file=sys.stderr)
        return 1
    write_gpl(entries, out)
    print("make_palette: wrote %s (256 entries)" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
